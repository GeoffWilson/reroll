#!/usr/bin/env python3
"""Writes src/game/gamefn.h: a prototype for every C function a hook sends an
original address to (src/main.c's hook tables), so calls by address
(GCALL(0x47aa00, car_boost)(slot)) are type-checked.

    tools/gamefn.py            (run from the repository root)
"""
import glob
import re

hooked = {}
sources = sorted(glob.glob("src/*.c")) + sorted(glob.glob("src/game/*.c")) + sorted(glob.glob("src/game/*.h"))
for path in sources:
    text = open(path).read()
    # hook tables: {"name", address, replacement, ...}
    for m in re.finditer(r'\{"(\w+)", (0x[0-9a-f]+), (\w+),', text):
        hooked.setdefault(m.group(3), int(m.group(2), 16))
    # declarations naming their original address: ... name(...); /* 0x41f2d0 ...
    for m in re.finditer(r'\b(\w+)\s*\([^;{()\n]*\);[ \t]*/\*\s*(0x4[0-9a-f]{5})\b', text):
        hooked.setdefault(m.group(1), int(m.group(2), 16))
# wrappers: the function a verification wrapper runs (main.c, "#define x_entry x")
main = open("src/main.c").read()
for m in re.finditer(r'^#define (\w+) (\w+) /\* nothing to verify against', main, re.M):
    if m.group(1) in hooked:
        hooked.setdefault(m.group(2), hooked[m.group(1)])

DEF = re.compile(r'^((?:const )?[A-Za-z_][\w ]*?[\s\*]+)(?:GAMEAPI\s+|WINAPI\s+)?(\**)(\w+)\s*\(([^)]*(?:\([^)]*\)[^)]*)*)\)\s*\{', re.M)
STD = re.compile(r'^(?:const )?(?:unsigned |signed )?(?:void|char|short|int|long|float|double|u?int(?:8|16|32|64)_t|size_t|uintptr_t|intptr_t|BOOL|DWORD|HANDLE)\b')
out, skipped = {}, []
def arch_at(text):
    """For each line: "x64" inside an x86-64-only #if block, "i386" inside an i386-only one, else ""."""
    out, stack = [], []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("#if"):
            stack.append("i386" if re.match(r"#if\s+defined\(__i386__\)", s) else
                         "x64" if re.match(r"#if\s+!\s*defined\(__i386__\)", s) else "")
        elif s.startswith("#else") and stack:
            stack[-1] = {"i386": "x64", "x64": "i386"}.get(stack[-1], "")
        elif s.startswith("#endif") and stack:
            stack.pop()
        out.append(next((k for k in reversed(stack) if k), ""))
    return out


arch = {}
for path in sorted(glob.glob("src/game/*.c")) + sorted(glob.glob("src/*.c")):
    text = open(path).read()
    where = arch_at(text)
    for m in DEF.finditer(text):
        ret, stars, name, params = m.group(1).strip(), m.group(2), m.group(3), re.sub(r"\s+", " ", m.group(4)).strip()
        if name not in hooked or name in out or ret.startswith("static"):
            continue
        head = m.group(0).split(name)[0]
        std = set(re.findall(r"^#define (\w+) __attribute__\(\(stdcall\)\)", text, re.M)) | {"WINAPI", "STDCALL"}
        words = set(re.findall(r"\b[A-Z][A-Z0-9_]+\b", ret)) - {"BOOL", "DWORD", "HANDLE", "GAMEAPI"}
        fast = set(re.findall(r"^#define (\w+) __attribute__\(\(fastcall\)\)", text, re.M))
        conv = "GSTDCALL" if words & std or "stdcall" in head else "GFASTCALL" if words & fast else "GAMEAPI"
        std |= fast
        if words - std:
            skipped.append("%s (%s: %s)" % (name, path, " ".join(sorted(words - std))))
            continue
        ret = re.sub(r"\b(GAMEAPI|%s)\b|__attribute__\(\(stdcall\)\)" % "|".join(std), "", ret).strip()
        parts = [p.strip() for p in params.split(",")] if params and params != "void" else []
        if not STD.match(ret) or any(not (STD.match(p) or p == "...") for p in parts):
            skipped.append("%s (%s)" % (name, path))
            continue
        arch[name] = where[text.count("\n", 0, m.start())]
        # declared outside the arch blocks: both builds reach it (by address)
        if arch[name] == "x64" and any(not where[text.count("\n", 0, d.start())]
                                       for d in re.finditer(r"\b%s\s*\([^;{)]*\)\s*;" % name, text)):
            arch[name] = ""
        if arch[name] == "i386":
            del arch[name]
            continue
        out[name] = "%s%s %s %s(%s); /* 0x%x */" % (ret, "" if ret.endswith("*") else "", conv, stars + name, params or "void", hooked[name])
lines = [
    "/* Generated by tools/gamefn.py: do not edit. */",
    "/* The C functions hooks send original addresses to, so a call by address",
    " * is checked against the function it reaches:",
    " *     GCALL(0x47aa00, car_boost)(slot)",
    " * calls 0x47aa00 (the hook there: verification, rumble... as before) with",
    " * car_boost's prototype. Game memory holds 32-bit pointers: GP(a) reads one",
    " * as a pointer, GMEM(a) makes an address a pointer. */",
    "#ifndef REROLL_GAME_GAMEFN_H",
    "#define REROLL_GAME_GAMEFN_H",
    "",
    '#include "runtime.h"',
    "",
    "#define GSTDCALL __attribute__((stdcall))",
    "#define GFASTCALL __attribute__((fastcall))",
    "#define GCALL(addr, name) ((__typeof__(&name))(uintptr_t)(addr))",
    "#ifndef GMEM",
    "#define GMEM(a) ((void *)(uintptr_t)(a))",
    "#endif",
    "#define GP(a) ((uint8_t *)(uintptr_t)*(const uint32_t *)(uintptr_t)(a))",
    "",
]
for k in sorted(out, key=lambda k: hooked[k]):
    if arch.get(k) == "x64":
        lines += ["#if !defined(__i386__)", out[k], "#endif"]
    else:
        lines.append(out[k])
lines += ["", "#endif", ""]
open("src/game/gamefn.h", "w").write("\n".join(lines))
print("%d prototypes, %d skipped (non-standard types):" % (len(out), len(skipped)))
for s in skipped:
    print("  " + s)
