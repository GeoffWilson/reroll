#!/usr/bin/env python3
"""Generates the native build's export tables (build/native/exports.c).

    tools/native_exports.py OUT.c native/kernel32.c native/user32.c ...

Every WINAPI function defined in native/<module>.c is an export of
<module>.dll (Rollcage.exe's imports are filled from these).
"""
import os
import re
import sys

DEF = re.compile(r'^(?!static)[A-Za-z_][\w \*]*?\bWINAPI\s+\*?\s*([A-Za-z_]\w*)\s*\(', re.M)


def main():
    out, sources = sys.argv[1], sys.argv[2:]
    modules = []
    for path in sources:
        module = os.path.splitext(os.path.basename(path))[0] + ".dll"
        names = sorted(set(DEF.findall(open(path).read())))
        modules.append((module, names))
    lines = ["/* Generated by tools/native_exports.py: do not edit. */", '#include "nt.h"', ""]
    for module, names in modules:
        for n in names:
            lines.append("extern char %s;" % n)
    lines.append("")
    for module, names in modules:
        ident = module.replace(".", "_")
        lines.append("static const struct nt_export %s[] = {" % ident)
        for n in names:
            lines.append('    {"%s", &%s},' % (n, n))
        lines.append("    {0, 0},")
        lines.append("};")
    lines.append("")
    lines.append("const struct nt_module nt_modules[] = {")
    for module, _ in modules:
        lines.append('    {"%s", %s},' % (module, module.replace(".", "_")))
    lines.append("    {0, 0},")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


main()
